//! The script of Claude Love, as data: a node a line, in reading order. A
//! node's id starts with its chapter (1-5); `Pick` is a choice of two or
//! three answers with what each does to the affection, `Roll` lets the
//! seed pick a line, `Warm` and `Burned` gate on what was won or burned,
//! and `End` names the ending the line closes. The dialogue is Korean; the
//! test in `dating.rs` holds every target to a node, every node to the
//! start, every path to an ending and every ending to a path.
use crate::dating::{Choice, Ending, Face, Next, Node, Who};
use Face::{Blush, Error, Happy, Plain, Sad, Shock, Think};
use Next::{Burned, End, Pick, Roll, To, Warm};
