pub(crate) const START: &str = "1-hello";

const fn say(id: &'static str, who: Who, face: Face, text: &'static str, next: Next) -> Node {
    Node {
        id,
        who,
        face,
        text,
        next,
    }
}

const fn pick(text: &'static str, warmth: i32, to: &'static str) -> Choice {
    Choice {
        text,
        warmth,
        burns: false,
        to,
    }
}

/// An answer that burns the quota.
const fn burn(text: &'static str, warmth: i32, to: &'static str) -> Choice {
    Choice {
        text,
        warmth,
        burns: true,
        to,
    }
}

